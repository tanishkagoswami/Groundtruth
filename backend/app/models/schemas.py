from pydantic import BaseModel
from typing import List, Dict, Any, Optional

class PaperRequest(BaseModel):
    arxiv_url: str
    arxiv_id: str
    github_url: Optional[str] = ""

class GitHubMetrics(BaseModel):
    repo_url: str
    friction_score: int
    dependency_flags: List[str]
    last_commit_date: str

class FeasibilityReport(BaseModel):
    paper_title: str
    github_metrics: Optional[GitHubMetrics] = None  # Now optional
    hardware_flags: List[str] = []
    dataset_validity: bool = False
    student_feasibility_score: int = 0
    citations: List[Dict[str, Any]] = []

class ScaffoldRequest(BaseModel):
    github_url: str
    hardware_flags: List[str]
    missing_files: List[str] # e.g., ["requirements.txt", "Dockerfile"]

class ScaffoldResponse(BaseModel):
    setup_script: str # The actual bash script or dockerfile generated by the LLM
    explanation: str